-- 敏感关键词库（标准词空间，AC 自动机数据源，双缓冲热更新）
CREATE TABLE patrol_keyword (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    keyword       VARCHAR(128) NOT NULL,
    category      VARCHAR(32)  NOT NULL,
    risk_level    SMALLINT     NOT NULL DEFAULT 1,
    enabled       SMALLINT     NOT NULL DEFAULT 1,
    source        VARCHAR(16)  NOT NULL DEFAULT 'MANUAL',
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_keyword PRIMARY KEY (id),
    CONSTRAINT uk_patrol_keyword_keyword UNIQUE (keyword)
);
COMMENT ON TABLE patrol_keyword IS '巡查关键词库';
COMMENT ON COLUMN patrol_keyword.keyword IS '标准词（归一化后的形态）';
COMMENT ON COLUMN patrol_keyword.category IS '分类: 飞单/资金/收费/其他';
COMMENT ON COLUMN patrol_keyword.risk_level IS '风险等级 1低 2中 3高';
COMMENT ON COLUMN patrol_keyword.source IS '来源: MANUAL/REVIEW回流';

-- 变体映射表（薇芯/vx/威信 -> 微信，人审回流持续补充）
CREATE TABLE patrol_variant_map (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    variant       VARCHAR(128) NOT NULL,
    canonical     VARCHAR(128) NOT NULL,
    source        VARCHAR(16)  NOT NULL DEFAULT 'MANUAL',
    enabled       SMALLINT     NOT NULL DEFAULT 1,
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_variant_map PRIMARY KEY (id),
    CONSTRAINT uk_patrol_variant_map_variant UNIQUE (variant)
);
COMMENT ON TABLE patrol_variant_map IS '对抗变体映射';
COMMENT ON COLUMN patrol_variant_map.variant IS '变体（归一化后形态）';
COMMENT ON COLUMN patrol_variant_map.canonical IS '标准词';

-- 白名单（官方渠道话术，避免误杀）
CREATE TABLE patrol_whitelist (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    phrase        VARCHAR(128) NOT NULL,
    enabled       SMALLINT     NOT NULL DEFAULT 1,
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_whitelist PRIMARY KEY (id),
    CONSTRAINT uk_patrol_whitelist_phrase UNIQUE (phrase)
);
COMMENT ON TABLE patrol_whitelist IS '巡查白名单';

-- 命中记录（供人审工作台与指标统计）
CREATE TABLE patrol_message_hit (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    message_id       BIGINT       NOT NULL,
    session_id       BIGINT       NOT NULL,
    sender_id        BIGINT       NOT NULL,
    sender_role      SMALLINT     NOT NULL,
    decision         SMALLINT     NOT NULL,
    reason           VARCHAR(32)  NOT NULL,
    hit_words        VARCHAR(512) NOT NULL,
    content_snapshot VARCHAR(1024) NOT NULL,
    review_status    SMALLINT     NOT NULL DEFAULT 0,
    gmt_create       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_message_hit PRIMARY KEY (id)
);
CREATE INDEX idx_patrol_message_hit_review ON patrol_message_hit (review_status, gmt_create);
CREATE INDEX idx_patrol_message_hit_sender ON patrol_message_hit (sender_id, gmt_create);
COMMENT ON TABLE patrol_message_hit IS '消息巡查命中记录';
COMMENT ON COLUMN patrol_message_hit.session_id IS '会话ID';
COMMENT ON COLUMN patrol_message_hit.sender_role IS '0求职者 1招聘者';
COMMENT ON COLUMN patrol_message_hit.decision IS '0放行 1提示 2拦截';
COMMENT ON COLUMN patrol_message_hit.hit_words IS '命中词，逗号分隔';
COMMENT ON COLUMN patrol_message_hit.content_snapshot IS '原文快照(脱敏)';
COMMENT ON COLUMN patrol_message_hit.review_status IS '0待人审 1确认 2误杀';

-- Kafka 消费幂等表（消息 ID + 处理版本，防重复消费）
CREATE TABLE patrol_message_idempotent (
    message_id    BIGINT    NOT NULL,
    version       BIGINT    NOT NULL DEFAULT 0,
    gmt_create    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_message_idempotent PRIMARY KEY (message_id)
);
COMMENT ON TABLE patrol_message_idempotent IS '消息巡查消费幂等';
