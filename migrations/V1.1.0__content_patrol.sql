-- ============================================================
-- 岗位巡查系统 - PostgreSQL 生产化表结构（演示）
--
-- 设计要点：
--   1. 指纹段倒排表：64bit 指纹拆 4 段各 16bit，每段一行，
--      依据抽屉原理，汉明距离 <= 3 的指纹必共享至少一段；
--   2. 联合索引 (shard_key, seg_idx, seg_val) 支撑"分片内段等值查询"；
--   3. 30 天滑动窗口：过期数据由定时任务清理，控制倒排规模与桶倾斜；
--   4. 岗位状态机表：version 字段 + 单调状态，防 Kafka 重复消费导致状态回跳。
--
-- PostgreSQL 方言差异见 V1.0.0__common_schema.sql 头部说明。
-- fingerprint 原为 BIGINT UNSIGNED，PG 的 BIGINT 装不下 2^64-1，改用 NUMERIC(20)。
-- ============================================================

-- 岗位状态机表
CREATE TABLE job_patrol_state (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id        BIGINT       NOT NULL,
    shard_key     VARCHAR(64)  NOT NULL,
    status        SMALLINT     NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 0,
    reason        VARCHAR(32)  NULL,
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_job_patrol_state PRIMARY KEY (id),
    CONSTRAINT uk_job_patrol_state_job UNIQUE (job_id)
);
CREATE INDEX idx_job_patrol_state_shard_status ON job_patrol_state (shard_key, status);
COMMENT ON TABLE job_patrol_state IS '岗位巡查状态机';
COMMENT ON COLUMN job_patrol_state.job_id IS '岗位ID';
COMMENT ON COLUMN job_patrol_state.shard_key IS '分片键: city|trade';
COMMENT ON COLUMN job_patrol_state.status IS '状态: 0待审 1通过 2疑似重复(复核) 3驳回 4下架';
COMMENT ON COLUMN job_patrol_state.version IS '版本号，幂等写入/单调性约束用';
COMMENT ON COLUMN job_patrol_state.reason IS '判定来源: SIMHASH_BODY / TITLE_EDIT_DISTANCE / MANUAL';

-- 指纹段倒排表（每个指纹写 4 行）
CREATE TABLE job_fingerprint_seg (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id        BIGINT       NOT NULL,
    shard_key     VARCHAR(64)  NOT NULL,
    seg_idx       SMALLINT     NOT NULL,
    seg_val       INTEGER      NOT NULL,
    fingerprint   NUMERIC(20)  NOT NULL,
    publish_time  TIMESTAMP    NOT NULL,
    CONSTRAINT pk_job_fingerprint_seg PRIMARY KEY (id),
    CONSTRAINT uk_job_fingerprint_seg_job_seg UNIQUE (job_id, seg_idx)
);
CREATE INDEX idx_job_fingerprint_seg_lookup ON job_fingerprint_seg (shard_key, seg_idx, seg_val, publish_time);
COMMENT ON TABLE job_fingerprint_seg IS 'SimHash 指纹段倒排';
COMMENT ON COLUMN job_fingerprint_seg.seg_idx IS '段序号 0-3';
COMMENT ON COLUMN job_fingerprint_seg.seg_val IS '该段16bit值(0-65535)';
COMMENT ON COLUMN job_fingerprint_seg.fingerprint IS '完整64bit指纹';
COMMENT ON COLUMN job_fingerprint_seg.publish_time IS '发布时间，滑动窗口清理依据';

-- 判重结果幂等表（Kafka 消费幂等：job_id + 版本号）
CREATE TABLE job_verdict (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id        BIGINT       NOT NULL,
    version       BIGINT       NOT NULL,
    duplicate     SMALLINT     NOT NULL,
    matched_job   BIGINT       NULL,
    body_hamming  INTEGER      NULL,
    title_edit    INTEGER      NULL,
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_job_verdict PRIMARY KEY (id),
    CONSTRAINT uk_job_verdict_job_version UNIQUE (job_id, version)
);
COMMENT ON TABLE job_verdict IS '岗位判重结果(幂等)';
COMMENT ON COLUMN job_verdict.version IS '岗位版本号，重复消费时拒绝旧版本';
COMMENT ON COLUMN job_verdict.matched_job IS '命中的已存在岗位';
COMMENT ON COLUMN job_verdict.body_hamming IS '正文最小汉明距离';
COMMENT ON COLUMN job_verdict.title_edit IS '标题编辑距离';

-- 人工复核队列
CREATE TABLE job_review_queue (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id        BIGINT       NOT NULL,
    matched_job   BIGINT       NOT NULL,
    body_hamming  INTEGER      NOT NULL,
    status        SMALLINT     NOT NULL DEFAULT 0,
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_job_review_queue PRIMARY KEY (id)
);
CREATE INDEX idx_job_review_queue_status ON job_review_queue (status, gmt_create);
COMMENT ON TABLE job_review_queue IS '疑似重复岗位人工复核队列';
COMMENT ON COLUMN job_review_queue.matched_job IS '相似的原岗位';
COMMENT ON COLUMN job_review_queue.body_hamming IS '两岗位指纹汉明距离';
COMMENT ON COLUMN job_review_queue.status IS '0待复核 1确认重复 2误杀(回流标注集)';

