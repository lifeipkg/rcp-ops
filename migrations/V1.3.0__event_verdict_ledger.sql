-- ============================================================
-- 平台级事件与裁决台账（dataway 白名单表的真源）
--
-- 与 job_verdict 的区别：job_verdict 是内容巡查线的岗位判重明细，
-- 本表是**跨巡查线统一**的事件台账，字段即 PatrolEvent / PatrolVerdict 契约的落库形态。
--
-- PostgreSQL 方言差异见 V1.0.0__common_schema.sql 头部说明。
-- ============================================================

CREATE TABLE patrol_event (
    event_id      VARCHAR(64)  NOT NULL,
    domain        VARCHAR(16)  NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 1,
    payload_json  JSONB        NULL,
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_event PRIMARY KEY (event_id)
);
CREATE INDEX idx_patrol_event_domain_create ON patrol_event (domain, gmt_create);
COMMENT ON TABLE patrol_event IS '巡查事件台账';
COMMENT ON COLUMN patrol_event.event_id IS '事件ID: job:123 / msg:456 / acc:.. / fund:..';
COMMENT ON COLUMN patrol_event.domain IS '巡查线: content/message/account/fund';
COMMENT ON COLUMN patrol_event.version IS '事件版本，单调递增';
COMMENT ON COLUMN patrol_event.payload_json IS '原始载荷，排障用';

CREATE TABLE patrol_verdict (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id      VARCHAR(64)  NOT NULL,
    domain        VARCHAR(16)  NOT NULL,
    decision      VARCHAR(16)  NOT NULL,
    score         INTEGER      NOT NULL DEFAULT 0,
    reason        VARCHAR(64)  NOT NULL DEFAULT '',
    degraded      SMALLINT     NOT NULL DEFAULT 0,
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_verdict PRIMARY KEY (id)
);
CREATE INDEX idx_patrol_verdict_event ON patrol_verdict (event_id);
CREATE INDEX idx_patrol_verdict_domain_decision ON patrol_verdict (domain, decision, gmt_create);
COMMENT ON TABLE patrol_verdict IS '巡查裁决台账';
COMMENT ON COLUMN patrol_verdict.decision IS 'PASS/WARN/LIMIT/EXTRA_REVIEW/INTERCEPT/BAN';
COMMENT ON COLUMN patrol_verdict.score IS '0-100 风险分';
COMMENT ON COLUMN patrol_verdict.degraded IS '1=巡查线降级转加审';
