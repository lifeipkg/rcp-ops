--   patrol.content.publish    岗位发布/更新    -> 内容巡查线 (job-patrol-system)
--   patrol.im.message         IM 消息发送      -> 消息巡查线 (message-patrol)
--   patrol.account.register   注册/登录        -> 账号巡查线
--   patrol.fund.grant         补贴发放申请      -> 资金巡查线
