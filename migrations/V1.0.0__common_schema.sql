-- ============================================================
-- 风控巡查平台 - 共同基建 PostgreSQL 表结构（演示）
--
-- 四条巡查线共用底座：幂等 / 状态机 / 规则 / 处置 / 复核 / 标注回流
--
-- PostgreSQL 方言说明（本组全部迁移脚本通用，写入方须一并遵守）：
--   1. 无 TINYINT / UNSIGNED：小枚举用 SMALLINT，计数用 BIGINT / INTEGER，
--      非负由应用层与 dataway 写入模板保证；64bit 无符号指纹另用 NUMERIC(20)
--      保住完整取值范围（BIGINT 只有 2^63-1）；
--   2. 无列内联 COMMENT：注释改用 COMMENT ON TABLE / COMMENT ON COLUMN；
--   3. 无表内 KEY / UNIQUE KEY 子句：唯一约束用内联 CONSTRAINT，索引独立建；
--      PG 的索引名在整个 schema 内唯一，故一律带表名前缀；
--   4. 无 ON UPDATE CURRENT_TIMESTAMP：gmt_modified 由写入方显式带
--      CURRENT_TIMESTAMP（dataway 写入模板已带），不建触发器——db-ops 的
--      MigrationService 按分号切分语句，plpgsql 函数体会被切碎；
--   5. JSON 用 JSONB，DATETIME 用 TIMESTAMP；无 ENGINE / CHARSET 子句；
--   6. 自增主键用 GENERATED BY DEFAULT AS IDENTITY，允许显式写入 id。
-- ============================================================

-- 消费幂等表（Kafka 统一幂等：event_id + version，重复消费拒绝旧版本）
CREATE TABLE patrol_idempotent (
    event_id      VARCHAR(64)  NOT NULL,
    domain        VARCHAR(16)  NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 0,
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_idempotent PRIMARY KEY (event_id)
);
CREATE INDEX idx_patrol_idempotent_domain ON patrol_idempotent (domain, gmt_create);
COMMENT ON TABLE patrol_idempotent IS '巡查消费幂等';
COMMENT ON COLUMN patrol_idempotent.event_id IS '事件ID: job:123 / msg:456 / fund:789';
COMMENT ON COLUMN patrol_idempotent.domain IS '巡查线: content/message/account/fund';

-- 巡查对象统一状态机（version + 单调状态，防乱序消息导致状态回跳）
CREATE TABLE patrol_object_state (
    event_id      VARCHAR(64)  NOT NULL,
    domain        VARCHAR(16)  NOT NULL,
    status        SMALLINT     NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 0,
    gmt_modified  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_object_state PRIMARY KEY (event_id)
);
CREATE INDEX idx_patrol_object_state_domain_status ON patrol_object_state (domain, status);
COMMENT ON TABLE patrol_object_state IS '巡查对象状态机';
COMMENT ON COLUMN patrol_object_state.event_id IS '对象ID';
COMMENT ON COLUMN patrol_object_state.status IS '0待审 1通过 2疑似(人审) 3拦截 4封禁 5申诉中';
COMMENT ON COLUMN patrol_object_state.version IS '版本号，只允许前进';

-- 风控规则表（热更新，规则快照原子切换）
CREATE TABLE patrol_rule (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    rule_key      VARCHAR(64)  NOT NULL,
    priority      INTEGER      NOT NULL DEFAULT 100,
    enabled       SMALLINT     NOT NULL DEFAULT 1,
    rule_json     JSONB        NOT NULL,
    decision      VARCHAR(16)  NOT NULL,
    reason        VARCHAR(32)  NOT NULL,
    gmt_modified  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_rule PRIMARY KEY (id),
    CONSTRAINT uk_patrol_rule_key UNIQUE (rule_key)
);
COMMENT ON TABLE patrol_rule IS '风控规则';
COMMENT ON COLUMN patrol_rule.rule_key IS '规则标识';
COMMENT ON COLUMN patrol_rule.priority IS '越小越优先，短路求值';
COMMENT ON COLUMN patrol_rule.rule_json IS '条件树(字段/操作符/值 AND 组合)';
COMMENT ON COLUMN patrol_rule.decision IS 'PASS/LIMIT/EXTRA_REVIEW/INTERCEPT/BAN';

-- 处置流水（分级处置：同一决策对不同对象的落地动作不同）
CREATE TABLE patrol_action_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id      VARCHAR(64)  NOT NULL,
    domain        VARCHAR(16)  NOT NULL,
    decision      VARCHAR(16)  NOT NULL,
    action        VARCHAR(32)  NOT NULL,
    operator      VARCHAR(32)  NOT NULL DEFAULT 'SYSTEM',
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_action_log PRIMARY KEY (id)
);
CREATE INDEX idx_patrol_action_log_event ON patrol_action_log (event_id);
CREATE INDEX idx_patrol_action_log_domain_time ON patrol_action_log (domain, gmt_create);
COMMENT ON TABLE patrol_action_log IS '处置流水';
COMMENT ON COLUMN patrol_action_log.action IS '落地动作: HIDE/LIMIT_POST/REVIEW/BLOCK/RECALL_GRANT';
COMMENT ON COLUMN patrol_action_log.operator IS 'SYSTEM=自动, 否则人审员工号';

-- 人工复核队列（各巡查线疑似样本统一入口）
CREATE TABLE patrol_review_queue (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id      VARCHAR(64)  NOT NULL,
    domain        VARCHAR(16)  NOT NULL,
    reason        VARCHAR(32)  NOT NULL,
    assignee      VARCHAR(32)  NULL,
    review_status SMALLINT     NOT NULL DEFAULT 0,
    reviewed_by   VARCHAR(32)  NULL,
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_review_queue PRIMARY KEY (id)
);
CREATE INDEX idx_patrol_review_queue_domain_status ON patrol_review_queue (domain, review_status, gmt_create);
COMMENT ON TABLE patrol_review_queue IS '人工复核队列';
COMMENT ON COLUMN patrol_review_queue.reason IS '进入原因: 疑似/评分区间/申诉';
COMMENT ON COLUMN patrol_review_queue.assignee IS '人审员工号';
COMMENT ON COLUMN patrol_review_queue.review_status IS '0待审 1确认违规 2误杀 3升级';

-- 标注回流表（误杀/漏放样本回流：驱动关键词库、变体映射、阈值再标定）
CREATE TABLE patrol_feedback (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    review_id     BIGINT       NOT NULL,
    domain        VARCHAR(16)  NOT NULL,
    label         VARCHAR(16)  NOT NULL,
    payload       JSONB        NULL,
    consumed      SMALLINT     NOT NULL DEFAULT 0,
    gmt_create    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_patrol_feedback PRIMARY KEY (id)
);
CREATE INDEX idx_patrol_feedback_consumed ON patrol_feedback (consumed, domain);
COMMENT ON TABLE patrol_feedback IS '标注回流';
COMMENT ON COLUMN patrol_feedback.review_id IS '来源复核单';
COMMENT ON COLUMN patrol_feedback.label IS 'FALSE_KILL误杀 / MISSED漏放';
COMMENT ON COLUMN patrol_feedback.payload IS '样本特征快照';
COMMENT ON COLUMN patrol_feedback.consumed IS '0未消费 1已回流到词库/阈值';

